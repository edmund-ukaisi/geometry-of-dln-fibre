# Substitute a generic 'resolved' A2 (upper-triangular-ish monomial chart) and see if det factors as
# monomial x unit in the remaining A1b vars.  Take A2 in a Case-2 pivot chart: A2 = [[1,*,*,*],
# [0,s,*,*],[0,0,t,*]] (rank-revealing).  Then Qb=A1b*A2 and det(QbQb^T) as poly in (a_i, s, t, *).
s,t = sp.symbols('s t', real=True)
star = sp.symbols('c0:6', real=True)
A2c = sp.Matrix([[1, star[0], star[1], star[2]],
                 [0, s,       star[3], star[4]],
                 [0, 0,       t,       star[5]]])
Qbc = sp.expand(A1b*A2c)
detGc = sp.expand((Qbc*Qbc.T).det())
gc = sp.Add.make_args(detGc)
g = gc[0]
for term in gc[1:]:
    g = sp.gcd(g, term)
print("  after a rank-revealing chart for A2, det(QbQb^T) has", len(gc), "monomials, gcd of terms =", g)
print("  => still gcd 1: no monomial factors out; the coupling to the minors of A1b (p=wedge^2 A1b)")
print("     survives.  Resolving A2 alone does NOT monomialize the product Gram det; the corank-2")
print("     Plucker coupling p^T G p remains -> the joint (product) principalisation is required.")
