"""
C4 : is {det(Qb Qb^T)=0} = {rank(A1b*A2) <= 1} a COORDINATE (toric) arrangement or a genuine
     DETERMINANTAL variety?  (toric => coordinate blow-ups suffice = BOUNDED; determinantal =>
     non-coordinate center forced = RESEARCH-GRADE.)
C5 : shared-vs-fresh toric RLCT gap (shared-divisor ledger necessity) + the corank-2 coupled value,
     via the toric RLCT LP  rlct(sum x^{2N_j}) = min_{w>0} (sum w)/(min_j <w, N_j>).
C6 : the pure route does not escape -- it relocates: the box Gamma-integral's outer residual is the
     SAME product-Gram det.  Confirm det(Qb Qb^T) is not a coordinate divisor even after resolving
     A2 alone (i.e. the coupling to p=wedge^2(A1b) survives).
"""
import sympy as sp
from itertools import combinations

print("="*80)
print("C4 : {det(Qb Qb^T)=0} for the 2x4 PRODUCT Qb=A1b*A2 -- coordinate or determinantal?")
print("="*80)

# Free 2x4 matrix first: {rank<=1} is the determinantal variety (cone over Segre P^1xP^3).
Y = sp.Matrix(2,4, sp.symbols('y0:8', real=True))
colpairs4 = list(combinations(range(4),2))
minfree = [sp.expand(Y[0,ij[0]]*Y[1,ij[1]]-Y[0,ij[1]]*Y[1,ij[0]]) for ij in colpairs4]
I = sp.polys.orderings  # noqa
# check: is any single 2x2 minor a monomial?  (coordinate divisor would need monomial generators)
print("  free 2x4: the 6 maximal minors are 2-term binomials (e.g. y0*y5 - y1*y4), NOT monomials:")
print("     example minor:", minfree[0])
print("     => {rank<=1} is generated by BINOMIALS/forms with incomparable support, an irreducible")
print("        determinantal variety of codim (2-1)(4-1)=3 (cone over Segre P^1 x P^3), NOT a union")
print("        of coordinate subspaces.  Blowing it up to principalise needs a NON-coordinate center.")

# Now the PRODUCT: det(Qb Qb^T) as a poly in (A1b, A2).  Its zero locus contains {rank A1b<=1} and
# {p . M2 = 0}.  Key: the Plucker vector p=wedge^2(A1b) enters as a QUADRATIC (minor) form -> the
# vanishing locus is cut by the 6 forms  minorQb_ij = sum_kl p_kl M2_kl,ij , each a 2x2 minor of a
# PRODUCT = a genuine bilinear-in-minors form, NOT a coordinate.
a = sp.symbols('a0:6', real=True); A1b = sp.Matrix(2,3,a)
b = sp.symbols('b0:12', real=True); A2 = sp.Matrix(3,4,b)
Qb = sp.expand(A1b*A2)
minorQb = [sp.expand(Qb[0,ij[0]]*Qb[1,ij[1]]-Qb[0,ij[1]]*Qb[1,ij[0]]) for ij in colpairs4]
print("  product 2x4: a maximal minor of Qb (a 2x2 minor of A1b*A2), # monomials:",
      [len(sp.Add.make_args(m)) for m in minorQb])
print("     example minor(Qb):", minorQb[0])
print("     => each is a sum of products (minor of A1b)*(minor of A2) [Cauchy-Binet], support")
print("        incomparable, gcd 1 -> NOT monomial in original coords; the ideal is determinantal.")

